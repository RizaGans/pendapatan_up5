CREATE TABLE IF NOT EXISTS projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS app_users (
  id SMALLINT PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_sessions (
  token_hash CHAR(64) PRIMARY KEY,
  user_id SMALLINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_app_sessions_expiry ON app_sessions(expires_at);

CREATE TABLE IF NOT EXISTS app_login_limits (
  key_hash CHAR(64) PRIMARY KEY,
  window_started TIMESTAMPTZ NOT NULL,
  attempts SMALLINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_app_login_limits_window ON app_login_limits(window_started);

CREATE TABLE IF NOT EXISTS app_years (
  year SMALLINT PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS monthly (
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  year SMALLINT NOT NULL,
  month SMALLINT NOT NULL,
  t1 BIGINT NOT NULL DEFAULT 0,
  t2 BIGINT NOT NULL DEFAULT 0,
  lain BIGINT NOT NULL DEFAULT 0,
  denda BIGINT NOT NULL DEFAULT 0,
  reward BIGINT NOT NULL DEFAULT 0,
  kerja_kurang BIGINT NOT NULL DEFAULT 0,
  suplisi BIGINT NOT NULL DEFAULT 0,
  kontrak BIGINT NOT NULL DEFAULT 0,
  status CHAR(1),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (project_id, year, month)
);

CREATE TABLE IF NOT EXISTS monthly_cell_status (
  project_id INTEGER NOT NULL,
  year SMALLINT NOT NULL,
  month SMALLINT NOT NULL,
  field SMALLINT NOT NULL,
  status CHAR(1) NOT NULL,
  PRIMARY KEY (project_id, year, month, field),
  FOREIGN KEY (project_id, year, month)
    REFERENCES monthly(project_id, year, month) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  project_id INTEGER,
  year SMALLINT,
  month SMALLINT,
  field VARCHAR(20),
  old_value VARCHAR(40),
  new_value VARCHAR(40),
  source VARCHAR(20) NOT NULL DEFAULT 'manual'
);

CREATE TABLE IF NOT EXISTS project_rows (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  label VARCHAR(120) NOT NULL,
  operation VARCHAR(8) NOT NULL DEFAULT 'add' CHECK (operation IN ('add', 'subtract')),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT project_row_label UNIQUE (project_id, label)
);

CREATE TABLE IF NOT EXISTS project_row_values (
  row_id INTEGER NOT NULL REFERENCES project_rows(id) ON DELETE CASCADE,
  year SMALLINT NOT NULL,
  month SMALLINT NOT NULL,
  amount BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (row_id, year, month)
);

CREATE TABLE IF NOT EXISTS project_base_rows (
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  field SMALLINT NOT NULL,
  label VARCHAR(120) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (project_id, field)
);
